// gen-page-emblems-sql.mjs — SCANS the whole live site for EMBLEMS (every
// page's WIKI_TOC.pageLogo + each flagship's wikiLogo) and writes migration
// 0010_page_emblems.sql, so the marks live in the TABLE instead of only as
// bespoke per-page markup. Re-run after changing a page's WIKI_TOC mark:
//   node scripts/gen-page-emblems-sql.mjs
// The output is committed (migrations are reviewed artifacts, like 0008's seed).
import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';
import { extractPageEmblem } from '../lib/page-emblem.mjs';

const ROOT = path.resolve(process.cwd(), '..');
// wiki id → the directories its pages live in (the home page is `<dir>/<dir>.html`)
const WIKIS = {
  'taco-bell': ['taco-bell', 'taco-bell/drinks', 'taco-bell/menus'],
  'apple': ['apple', 'apple/ipod-touch'],
  'fallout': ['fallout'],
  'smurfs-village': ['smurfs-village'],
  'doodle-jump': ['doodle-jump'],
};
const HOME_FILE = { 'taco-bell': 'taco-bell.html', 'apple': 'apple.html', 'fallout': 'fallout.html', 'smurfs-village': 'smurfs-village.html', 'doodle-jump': 'doodle-jump.html' };

const sq = (s) => String(s).replace(/'/g, "''");
const fmTitle = (txt, fallback) => {
  const m = txt.match(/^---\n([\s\S]*?)\n---/);
  try {
    const fm = m ? yaml.load(m[1]) || {} : {};
    return String(fm.title || fallback).replace(/<br\s*\/?>/gi, ' ').trim();
  } catch { return fallback; }
};

const pageRows = [];
const wikiMarks = [];
for (const [wikiId, dirs] of Object.entries(WIKIS)) {
  let homeMark = null, anyWikiLogo = null;
  for (const dir of dirs) {
    const abs = path.join(ROOT, dir);
    if (!fs.existsSync(abs)) continue;
    for (const f of fs.readdirSync(abs).filter((x) => x.endsWith('.html')).sort()) {
      const txt = fs.readFileSync(path.join(abs, f), 'utf8');
      if (!txt.includes('WIKI_TOC')) continue;
      const icon = extractPageEmblem(txt);
      const isHome = f === HOME_FILE[wikiId];
      // EVERY scanned page gets a row — a null icon clears a previously
      // seeded mark, and the identity-only row is the page's seat in the
      // table (no published revision → invisible to readers)
      pageRows.push({
        wiki: wikiId,
        id: isHome ? `${wikiId}-home` : f.replace(/\.html$/, ''),
        slug: f,
        title: fmTitle(txt, f.replace(/\.html$/, '')),
        type: isHome ? 'home' : 'standard',
        icon,
      });
      // the WIKI's mark: the home's wikiLogo, else ANY page's wikiLogo (the
      // sub-pages carry the real mark where the home leaves it out — Taco
      // Bell's bell lives on its listing pages), else the home's pageLogo
      const wl = extractPageEmblem(txt, 'wikiLogo');
      if (wl && (isHome || !anyWikiLogo)) anyWikiLogo = wl;
      if (isHome && icon) homeMark = icon;
    }
  }
  const wm = anyWikiLogo || homeMark;
  if (wm) wikiMarks.push({ wiki: wikiId, icon: wm });
}

const lines = pageRows.map((r) =>
  `  ('${sq(r.wiki)}', '${sq(r.id)}', '${sq(r.slug)}', '${sq(r.title)}', '${sq(r.type)}', ${r.icon ? `'${sq(JSON.stringify(r.icon))}'::jsonb` : 'null'})`);

const sql = `-- 0010_page_emblems.sql — PAGE EMBLEMS live in the table (owner's rule,
-- late Oct 2026). Adds pages.icon (the page's small MARK, master media
-- pattern — same jsonb shape as wikis.icon: {"kind":"glyph","name":…} |
-- {"kind":"art","src":…}) and SEEDS every emblem scanned off the live
-- site's WIKI_TOC pageLogo blocks (generated by
-- _builder/scripts/gen-page-emblems-sql.mjs — re-run it after a mark
-- changes page-side). Also lifts each flagship's hand-drawn wikiLogo into
-- wikis.icon where the wiki still wears the auto letter default.
-- Idempotent: re-runs refresh the icons only.
-- NOTE: the 5 iPod pages share one 84KB photo PNG as their mark — too heavy
-- for an inline seed; they stay page-side until Storage uploads land.

alter table public.pages add column if not exists icon jsonb;

-- ── the scanned PAGE emblems (upsert; stub rows carry just identity + mark —
-- they hold no published revision, so readers never see them as pages) ──
insert into public.pages (wiki_id, id, slug, title, type, icon) values
${lines.join(',\n')}
on conflict (wiki_id, id) do update set icon = excluded.icon;

-- ── the flagship WIKI emblems (hand-drawn wikiLogo marks) — fill where the
-- wiki still wears the auto default OR a previously SEEDED mark (an inline
-- data-uri svg, i.e. an earlier run of this file); a glyph pick or an image
-- URL the owner set is never touched ──
${wikiMarks.map((w) =>
  `update public.wikis set icon = '${sq(JSON.stringify(w.icon))}'::jsonb\n  where id = '${sq(w.wiki)}' and (icon is null or icon->>'kind' = 'auto'\n    or (icon->>'kind' = 'art' and icon->>'src' like 'data:image/svg+xml;base64,%'));`).join('\n')}
`;

const out = path.join(process.cwd(), 'supabase', 'migrations', '0010_page_emblems.sql');
fs.writeFileSync(out, sql);
console.log(`wrote ${out} — ${pageRows.length} page emblems, ${wikiMarks.length} wiki marks`);
for (const r of pageRows) console.log(`  ${r.wiki} · ${r.id} (${(JSON.stringify(r.icon).length / 1024).toFixed(1)}KB)`);
