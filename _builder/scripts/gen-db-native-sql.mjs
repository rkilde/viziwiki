// gen-db-native-sql.mjs — PROJECT DBNATIVE slice 1: write migration
// 0011_db_native_content.sql, backfilling EVERY extracted flagship page's
// content into the database as a PUBLISHED revision, so the reader serves
// the flagship wikis from rows like any originated wiki.
//   node scripts/gen-db-native-sql.mjs      (run from _builder, after gen)
// Every doc is validated against the grammar AND rendered through the
// derived renderer before a line of SQL is written — a doc the reader
// can't serve fails the generation.
// SAFETY: a page that ALREADY has rows in the database (saved from the
// builder) is left untouched — the backfill fills only absent pages.
import fs from 'node:fs';
import path from 'node:path';
import { flagshipDocs } from '../lib/backfill-docs.mjs';
import { docToRows, validateDoc } from '../lib/content-map.mjs';
import { buildPolicy } from '../lib/policy.mjs';
import { createRenderer } from '../lib/render-core.mjs';

const data = (f) => JSON.parse(fs.readFileSync(path.join(process.cwd(), 'data', f), 'utf8'));
const grammar = data('grammar.json');
const renderer = createRenderer(data('includes.json'), buildPolicy(grammar), data('visuals.json'));
const sq = (s) => String(s).replace(/'/g, "''");

const docs = flagshipDocs();
const blocks = [];
for (const p of docs) {
  const v = validateDoc(p.doc, grammar);
  if (!v.ok) { console.error(`✗ ${p.wiki}/${p.id}: ${v.errors.join('; ')}`); process.exit(1); }
  const html = renderer.renderBody(p.doc, p.isHome);
  if (!html || html.length < 200) { console.error(`✗ ${p.wiki}/${p.id}: renders empty`); process.exit(1); }
  const rows = docToRows(p.doc).map((r) =>
    `  ('${sq(p.wiki)}', '${sq(p.id)}', ${r.position}, '${sq(r.component)}', '${sq(JSON.stringify(r.data))}'::jsonb)`);
  blocks.push(`-- ── ${p.wiki} / ${p.id} (${p.doc.sections.length + 2} sections) ──
insert into public.pages (wiki_id, id, slug, title, type) values
  ('${sq(p.wiki)}', '${sq(p.id)}', '${sq(p.slug)}', '${sq(p.title)}', '${sq(p.type)}')
on conflict (wiki_id, id) do update set slug = excluded.slug, title = excluded.title, type = excluded.type;
insert into public.sections (wiki_id, page_id, position, component, data)
select * from (values
${rows.join(',\n')}
) as v(wiki_id, page_id, position, component, data)
where not exists (select 1 from public.sections s
  where s.wiki_id = '${sq(p.wiki)}' and s.page_id = '${sq(p.id)}');`);
}

const sql = `-- 0011_db_native_content.sql — PROJECT DBNATIVE, slice 1: the flagship
-- wikis' PAGE CONTENT moves into the database. Every extracted live page
-- (Taco Bell ×16 · Apple ×7) lands as section rows + ONE published
-- revision, so the reader (/read/<wiki>/<page>) serves it like any
-- originated wiki — same renderer, same canon CSS, cache-until-edited.
-- GENERATED by _builder/scripts/gen-db-native-sql.mjs from the extraction
-- output (which derives from the pages' own front matter). Idempotent, and
-- SAFE for builder work: a page that already has rows in the database is
-- left untouched — the backfill fills only pages the DB doesn't hold yet.
-- (The revision/pointer block reuses 0004's backfill pattern.)

${blocks.join('\n\n')}

-- ── one PUBLISHED revision per backfilled page (0004's pattern) ──
insert into public.revisions (wiki_id, page_id, doc, status, author_email, note)
select s.wiki_id, s.page_id,
  jsonb_build_object(
    'hero',     coalesce((select h.data from public.sections h where h.wiki_id = s.wiki_id and h.page_id = s.page_id and h.position = 0), '{}'::jsonb),
    'overview', coalesce((select o.data from public.sections o where o.wiki_id = s.wiki_id and o.page_id = s.page_id and o.position = 1), '{}'::jsonb),
    'sections', coalesce((select jsonb_agg(jsonb_build_object('type', b.component, 'data', b.data) order by b.position)
                          from public.sections b where b.wiki_id = s.wiki_id and b.page_id = s.page_id and b.position >= 2), '[]'::jsonb)
  ),
  'published', 'system', 'DBNATIVE backfill from the git-authored page'
from (select distinct wiki_id, page_id from public.sections) s
where not exists (select 1 from public.revisions r where r.wiki_id = s.wiki_id and r.page_id = s.page_id);

select set_config('vizi.publishing', '1', false);   -- the backfill may move the pointer
update public.pages p
set published_rev = (select max(r.id) from public.revisions r
                     where r.wiki_id = p.wiki_id and r.page_id = p.id and r.status = 'published')
where p.published_rev is null
  and exists (select 1 from public.sections s where s.wiki_id = p.wiki_id and s.page_id = p.id);
select set_config('vizi.publishing', '', false);
`;

const out = path.join(process.cwd(), 'supabase', 'migrations', '0011_db_native_content.sql');
fs.writeFileSync(out, sql);
console.log(`wrote ${out} — ${docs.length} pages (${(sql.length / 1024).toFixed(0)}KB), every doc grammar-valid + renderer-verified`);
for (const p of docs) console.log(`  ${p.wiki.padEnd(10)} ${p.id.padEnd(34)} ${p.doc.sections.length + 2} sections`);
